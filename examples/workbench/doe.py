"""Reproducible toy process responses, not validated semiconductor process models."""
import csv
import json
from pathlib import Path

import numpy as np

DATA = Path(__file__).resolve().parents[2] / 'data/demo' / 'doe'
SPECS = {
    'pvd': {
        'features': {'power_W': [200, 600], 'pressure_mTorr': [2, 8], 'temperature_C': [100, 300],
                     'bias_V': [-100, -20], 'argon_sccm': [20, 60], 'time_min': [5, 15]},
        'responses': {'thickness_nm': 'target', 'uniformity_error_pct': 'smaller',
                      'roughness_nm': 'smaller', 'resistivity_uohm_cm': 'smaller'},
    },
    'cvd': {
        'features': {'temperature_C': [300, 450], 'pressure_Torr': [0.5, 2], 'precursor_sccm': [10, 40],
                     'carrier_sccm': [100, 300], 'plasma_W': [50, 250], 'time_min': [5, 15]},
        'responses': {'thickness_nm': 'target', 'uniformity_error_pct': 'smaller',
                      'refractive_index': 'target', 'wet_etch_rate_nm_min': 'smaller'},
    },
}


def generate(output=DATA, *, seed=20261020):
    """Write 15 runs per process: 12 stratified random settings + 3 noisy center replicates."""
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    manifest = {'synthetic': True, 'seed': seed, 'total_runs': 30,
                'license': 'MIT; generated by this repository, no external measurements.',
                'design': 'Per process: 12 Latin-hypercube-like stratified settings and 3 center replicates; not a full factorial or orthogonal array.',
                'limitations': 'Toy equations with additive noise. Not equipment recipes, calibrated predictions, or proof of causal effects. Analyze PVD and CVD separately.',
                'processes': {}}
    for process, spec in SPECS.items():
        # Independently permuted strata in each input dimension.
        z = np.column_stack([(rng.permutation(12) + rng.random(12)) / 12 for _ in spec['features']])
        z = np.vstack([z, np.full((3, 6), .5)])
        physical = np.column_stack([lo + z[:, i] * (hi-lo) for i, (lo, hi) in enumerate(spec['features'].values())])
        a, b, c, d, e, f = z.T
        if process == 'pvd':
            rate = 9 + 13*a - 2*b + 2*a*b + .8*c
            response = np.column_stack([
                physical[:, 5]*rate + rng.normal(0, 2, 15),
                1.2 + 4*(b-.45)**2 + 1.5*(e-.5)**2 + .5*a + rng.normal(0, .08, 15),
                .6 + 1.8*b + .6*a - .5*c - .25*d + rng.normal(0, .06, 15),
                8 + 2*b - 2*c - 1.2*d + .8*b*d + rng.normal(0, .12, 15),
            ])
            equations = ['rate=9+13a-2b+2ab+0.8c; thickness=time*rate+N(0,2)',
                         'uniformity=1.2+4(b-.45)^2+1.5(e-.5)^2+.5a+N(0,.08)',
                         'roughness=.6+1.8b+.6a-.5c-.25d+N(0,.06)',
                         'resistivity=8+2b-2c-1.2d+.8bd+N(0,.12)']
        else:
            rate = 5 + 8*a + 6*c + 3*e + 2*a*c - 1.5*b
            response = np.column_stack([
                physical[:, 5]*rate + rng.normal(0, 2.5, 15),
                1 + 2.5*(b-.4)**2 + 2*(d-.6)**2 + .6*c + rng.normal(0, .07, 15),
                1.6 + .18*a + .14*e - .08*c + rng.normal(0, .006, 15),
                35 - 12*a - 8*e + 5*c + 3*b + rng.normal(0, .6, 15),
            ])
            equations = ['rate=5+8a+6c+3e+2ac-1.5b; thickness=time*rate+N(0,2.5)',
                         'uniformity=1+2.5(b-.4)^2+2(d-.6)^2+.6c+N(0,.07)',
                         'index=1.6+.18a+.14e-.08c+N(0,.006)',
                         'etch=35-12a-8e+5c+3b+N(0,.6)']
        headers = ['run_id', 'process', 'synthetic', 'design_point', *spec['features'], *spec['responses']]
        with (output / f'{process}_15.csv').open('w', newline='', encoding='utf-8') as handle:
            writer = csv.writer(handle)
            writer.writerow(headers)
            for i, (inputs, outputs) in enumerate(zip(physical, response)):
                writer.writerow([f'{process.upper()}-{i+1:02}', process.upper(), 'true',
                                 'center_replicate' if i >= 12 else 'stratified',
                                 *np.round(inputs, 6), *np.round(outputs, 6)])
        manifest['processes'][process] = {**spec, 'file': f'{process}_15.csv', 'rows': 15,
                                        'equations': equations, 'variables': 'a..f are input columns in listed order, scaled to [0,1]; N is independent Gaussian noise.'}
    (output / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    return manifest


if __name__ == '__main__':
    generate()
    print(DATA)
